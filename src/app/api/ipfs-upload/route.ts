import { NextRequest, NextResponse } from "next/server";
import JSZip from 'jszip';
import { uploadToIPFS, uploadDirectoryToIPFS } from '@/lib/ipfs';

export async function POST(req: NextRequest) {
  const { deliverable } = await req.json();

  try {
    // Generate file based on deliverable type
    let fileContent: Uint8Array;
    let contentType: string;
    let filename: string;

    switch (deliverable.type) {
      case "presentation":
        fileContent = await generatePresentation(deliverable);
        contentType = "application/vnd.openxmlformats-officedocument.presentationml.presentation";
        filename = `${deliverable.name}.pptx`;
        break;
      
      case "pdf":
        fileContent = await generatePDF(deliverable);
        contentType = "application/pdf";
        filename = `${deliverable.name}.pdf`;
        break;
      
      case "codebase":
        fileContent = await generateCodebaseZip(deliverable);
        contentType = "application/zip";
        filename = `${deliverable.name}.zip`;
        break;
      
      case "image":
        fileContent = await generateImage(deliverable);
        contentType = "image/png";
        filename = `${deliverable.name}.png`;
        break;
      
      case "document":
        fileContent = await generateDocument(deliverable);
        contentType = "application/vnd.openxmlformats-officedocument.wordprocessingml.document";
        filename = `${deliverable.name}.docx`;
        break;
      
      case "spreadsheet":
        fileContent = await generateSpreadsheet(deliverable);
        contentType = "application/vnd.openxmlformats-officedocument.spreadsheetml.sheet";
        filename = `${deliverable.name}.xlsx`;
        break;
      
      default:
        throw new Error("Unsupported deliverable type");
    }

    const appUrl = req.nextUrl.origin;
    
    // Auth context for User/Project isolation
    const { auth } = await import("@/auth");
    const session = await auth();
    const userId = session?.user?.id || session?.user?.email || "anonymous_user";
    const projectId = deliverable.id || deliverable.name || "unnamed_project";
    
    // Sanitize ID strings for filesystem use
    const sanitizePath = (str: string) => str.replace(/[^a-zA-Z0-9_-]/g, "_").substring(0, 40);
    const orgPath = `${sanitizePath(userId)}/${sanitizePath(projectId)}`;

    // Upload to IPFS for decentralized storage
    let ipfsResult;
    if (deliverable.type === "codebase") {
      // For codebases, upload as directory
      const files = parseCodebaseFiles(deliverable.content, deliverable.name);
      ipfsResult = await uploadDirectoryToIPFS(files, deliverable.name, appUrl, orgPath);
    } else {
      // For single files, upload directly
      ipfsResult = await uploadToIPFS(fileContent, filename, contentType, appUrl, orgPath);
    }

    // Return IPFS information
    return NextResponse.json({
      success: true,
      ipfsHash: ipfsResult.hash,
      ipfsUrl: ipfsResult.url,
      filename: filename,
      size: ipfsResult.size,
      contentType: contentType,
      gatewayUrl: ipfsResult.url,
      message: `File successfully ${ipfsResult.url.includes('api/ipfs') ? 'emulated locally' : 'uploaded to IPFS'} and pinned for persistence`
    });

  } catch (error) {
    console.error('IPFS file generation error:', error);
    return NextResponse.json(
      { 
        success: false,
        error: 'Failed to generate and upload file to IPFS: ' + (error as Error).message
      },
      { status: 500 }
    );
  }
}

