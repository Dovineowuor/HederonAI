// Function to get relevant SOP based on challenge analysis
export function getIndustrySOP(industry: string, category: string): any {
  const industryData = INDUSTRY_SOPS[industry as keyof typeof INDUSTRY_SOPS];
  if (!industryData) return null;
  return industryData[category as keyof typeof industryData] || null;
}

// Function to detect industry from challenge description
export function detectIndustryFromChallenge(challenge: string): string | null {
  const keywords: Record<string, string[]> = {
    saas: ['software', 'subscription', 'platform', 'api', 'cloud', 'mvp', 'startup'],
    ecommerce: ['store', 'shop', 'retail', 'product', 'inventory', 'shipping', 'cart', 'checkout'],
    fintech: ['bank', 'finance', 'payment', 'investment', 'trading', 'crypto', 'lending'],
    healthcare: ['medical', 'health', 'patient', 'hospital', 'clinic', 'pharma', 'insurance'],
    manufacturing: ['factory', 'production', 'supply chain', 'machinery', 'assembly'],
    retail: ['store', 'shop', 'customer', 'sales', 'merchandise'],
    education: ['learning', 'school', 'course', 'student', 'teacher', 'curriculum'],
    realestate: ['property', 'real estate', 'rental', 'housing', 'mortgage', 'broker']
  };
  
  const lowerChallenge = challenge.toLowerCase();
  
  for (const [industry, industryKeywords] of Object.entries(keywords)) {
    if (industryKeywords.some((keyword: string) => lowerChallenge.includes(keyword))) {
      return industry;
    }
  }
  
  return null;
}
